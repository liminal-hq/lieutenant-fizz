// Usage: bun scripts/build-play-graphics.ts [--check]
//   --check  fail if the committed SVGs differ from what this would write (used by validate)
//
// The feature graphic is a clean version of the README hero: the same Planet Zargoth scene (the saucer, crystals,
// cake building and chocolate river), a taller canvas with more sky, and only the title and episode name, drawn from
// the Fizz glyph grids so it needs no font. The icon is the app icon without its rounded corners, because Play
// applies its own mask. Render the PNGs Play wants with rsvg-convert (see assets/play-store/README.md).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FACES, faceEntries, type Entry } from '../packages/engine/src/font/build';
import { traceOutline } from '../packages/engine/src/font/outline';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (file: string): string => readFileSync(join(root, file), 'utf8');

const HEADER = [
  '<!-- (c) Copyright 2026 Liminal HQ, Scott Morris -->',
  '<!-- SPDX-License-Identifier: Apache-2.0 OR MIT -->',
  '<!-- Generated by scripts/build-play-graphics.ts: edit that, not this. -->',
].join('\n');

const glyphs = (file: string): Map<number, Entry> => {
  const spec = FACES.find((f) => f.file === file);
  if (!spec) throw new Error(`no face ${file}`);
  return new Map(faceEntries(spec).map((e) => [e.cp, e]));
};
const bold = glyphs('fizz-bold');
const regular = glyphs('fizz-regular');

function widthOf(text: string, face: Map<number, Entry>): number {
  let w = 0;
  for (const ch of text) {
    const e = face.get(ch.codePointAt(0) as number);
    if (!e) throw new Error(`Fizz has no glyph for ${JSON.stringify(ch)}`);
    w += e.placed.adv;
  }
  return w;
}

/** One line of text as a filled path, its first cell's top-left at (x, y), `s` pixels per glyph pixel. */
function drawText(
  text: string,
  face: Map<number, Entry>,
  x: number,
  y: number,
  s: number,
  fill: string,
): string {
  let d = '';
  let pen = 0;
  for (const ch of text) {
    const e = face.get(ch.codePointAt(0) as number);
    if (!e) throw new Error(`Fizz has no glyph for ${JSON.stringify(ch)}`);
    for (const c of traceOutline(e.placed.rows, 9, pen + e.placed.ox)) {
      d += c.map((p, i) => `${i ? 'L' : 'M'}${x + p.x * s} ${y + (9 - p.y) * s}`).join('') + 'Z';
    }
    pen += e.placed.adv;
  }
  return `<path fill="${fill}" d="${d}"/>`;
}

/** Text with pixel shadows: each layer is the same text moved down by `dy` glyph pixels, drawn first. */
function shadowed(
  text: string,
  face: Map<number, Entry>,
  x: number,
  y: number,
  s: number,
  fill: string,
  shadows: [string, number][] = [],
): string {
  const layers = [...shadows].reverse().map(([f, dy]) => drawText(text, face, x, y + dy * s, s, f));
  return layers.join('') + drawText(text, face, x, y, s, fill);
}

function featureGraphic(): string {
  const hero = read('assets/hero.svg');
  const defs = hero.slice(hero.indexOf('<defs>') + '<defs>'.length, hero.indexOf('</defs>'));
  const from = hero.indexOf('<g clip-path="url(#frame)">');
  const to = hero.indexOf('<!-- Eyebrow, title');
  if (from < 0 || to < 0)
    throw new Error('assets/hero.svg has changed shape: update build-play-graphics.ts');
  // The hero's scene without its rounded frame: Play wants a plain rectangle.
  const scene = hero.slice(from, to).trimEnd().replace('<g clip-path="url(#frame)">', '<g>');

  // More sky above the scene, whose own starfield covers only its 320 px. Seeded, so the output is stable.
  let seed = 7;
  const rnd = (): number => (seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296;
  let stars = '';
  for (let i = 0; i < 70; i++) {
    const x = Math.round(rnd() * 1024);
    const y = Math.round(rnd() * 250);
    const size = rnd() < 0.15 ? 2 : 1;
    const opacity = (0.35 + rnd() * 0.5).toFixed(2);
    stars += `<rect x="${x}" y="${y}" width="${size}" height="${size}" opacity="${opacity}"/>`;
  }

  const title = 'Lieutenant Fizz';
  let scale = 7;
  while (widthOf(title, bold) * scale > 540) scale--;
  const BLACK = '#000000';
  const ROSE = '#f43f5e';
  const x = 56;
  const text = [
    shadowed('Ben Blaze in', bold, x + 2, 52, 3, '#ffaa40', [[BLACK, 1]]),
    shadowed(title, bold, x, 92, scale, '#ffffff', [
      [ROSE, 1],
      [BLACK, 2],
    ]),
    shadowed('Episode 1 · The Cocoa Caper', regular, x + 3, 92 + 11 * scale + 40, 3, '#b4bfce', [
      [BLACK, 1],
    ]),
  ].join('');

  return [
    HEADER,
    '<svg width="1024" height="500" viewBox="0 0 1024 500" xmlns="http://www.w3.org/2000/svg" role="img" aria-labelledby="t d">',
    '<title id="t">Lieutenant Fizz</title>',
    '<desc id="d">Google Play feature graphic: Lieutenant Fizz, Episode 1, The Cocoa Caper, over Planet Zargoth with a spaghetti-and-meatballs flying saucer, crystals, a cake building and a chocolate river.</desc>',
    `<defs>${defs}</defs>`,
    '<rect width="1024" height="500" fill="url(#bg)"/>',
    '<circle cx="150" cy="120" r="170" fill="#ffaa40" opacity="0.05"/>',
    `<g fill="#e0e0e0">${stars}</g>`,
    `<g transform="translate(-176,180)">${scene}</g>`,
    `<g aria-hidden="true">${text}</g>`,
    '</svg>',
    '',
  ].join('\n');
}

function icon(): string {
  const source = read('assets/icon/fizz-icon.svg');
  if (!source.includes(' rx="64"'))
    throw new Error('assets/icon/fizz-icon.svg has changed shape: update build-play-graphics.ts');
  return `${HEADER}\n${source.replace(' rx="64"', '')}`;
}

const FILES: Record<string, () => string> = {
  'assets/play-store/feature-graphic-1024x500.svg': featureGraphic,
  'assets/play-store/icon-512.svg': icon,
};

const check = process.argv.includes('--check');
let stale = false;
for (const [file, make] of Object.entries(FILES)) {
  const path = join(root, file);
  const next = make();
  let current = '';
  try {
    current = readFileSync(path, 'utf8');
  } catch {
    // not written yet
  }
  if (current === next) continue;
  if (check) stale = true;
  else writeFileSync(path, next);
}
if (check && stale) {
  console.error('The Play store graphics are out of date. Run: bun run build:play-graphics');
  process.exit(1);
}
console.log(check ? 'Play store graphics are up to date.' : 'Play store graphics written.');
